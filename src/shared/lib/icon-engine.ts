export function renderIconElement(el: Element): void {
	if (!el.classList.contains('material-symbols-outlined')) return;

	// If an <svg> is already inside and no new text node was injected by SolidJS, skip
	const hasSvg = el.querySelector('svg') !== null;
	let rawText = '';

	for (let i = 0; i < el.childNodes.length; i++) {
		const node = el.childNodes[i];
		if (node.nodeType === Node.TEXT_NODE) {
			const val = (node.textContent || '').trim();
			if (val) rawText = val;
		}
	}

	if (!rawText && hasSvg) return;
	if (!rawText) {
		rawText = (el.getAttribute('data-mg-icon') || '').trim();
	}
	if (!rawText) return;

	const iconName = rawText.toLowerCase();
	const pathMarkup = ICON_PATHS[iconName] || DEFAULT_PATH;

	el.setAttribute('data-mg-icon', iconName);
	el.setAttribute('data-mg-svg', '1');
	el.setAttribute('aria-hidden', 'true');
	el.innerHTML = `<svg viewBox="0 0 24 24" width="1em" height="1em" fill="currentColor" focusable="false" style="display:block;width:1em;height:1em;pointer-events:none;flex-shrink:0;">${pathMarkup}</svg>`;
}

export function renderIconsInRoot(root: ParentNode = document): void {
	if (root instanceof Element && root.classList.contains('material-symbols-outlined')) {
		renderIconElement(root);
	}
	const nodes = root.querySelectorAll('.material-symbols-outlined');
	for (let i = 0; i < nodes.length; i++) {
		renderIconElement(nodes[i]);
	}
}

let observerInitialized = false;

export function initIconEngine(): void {
	if (typeof document === 'undefined' || observerInitialized) return;
	observerInitialized = true;

	renderIconsInRoot(document);

	const observer = new MutationObserver((mutations) => {
		for (let i = 0; i < mutations.length; i++) {
			const m = mutations[i];
			if (m.type === 'characterData') {
				const parent = m.target.parentElement;
				if (parent?.classList.contains('material-symbols-outlined')) {
					renderIconElement(parent);
				}
			} else if (m.type === 'childList') {
				if (
					m.target instanceof Element &&
					m.target.classList.contains('material-symbols-outlined')
				) {
					renderIconElement(m.target);
				}
				for (let j = 0; j < m.addedNodes.length; j++) {
					const node = m.addedNodes[j];
					if (node instanceof Element) {
						renderIconsInRoot(node);
					} else if (node.nodeType === Node.TEXT_NODE && m.target instanceof Element) {
						if (m.target.classList.contains('material-symbols-outlined')) {
							renderIconElement(m.target);
						}
					}
				}
			}
		}
	});

	observer.observe(document.documentElement, {
		childList: true,
		subtree: true,
		characterData: true,
	});
}
